/**
 * The two rules that must appear verbatim in every prompt, exported so tests can assert on the
 * canonical text instead of a copy of it that drifts.
 */


/**
 * Build the controlled-side prompt.
 *
 * The prose is data (`./prompt-sections.js`); this function only fills variables, numbers the steps, and
 * embeds the one block that must be byte-exact — the public key.
 *
 * @param options - `{ publicKey, user, host, port }`. The port is the one the controller will actually
 *   connect to, so the prompt never hardcodes 22.
 * @returns the prompt text.
 */
export function buildSetupPrompt(options) {
  const publicKey = String(options.publicKey ?? '').trim();
  const user = String(options.user ?? '').trim();
  const host = String(options.host ?? '').trim();
  // An account is OPTIONAL, and its absence is not a failure. The account lives on the controlled machine, and
  // the prompt already sends that machine to find it and report back — so requiring the controller to name it
  // first was the controller demanding information only the other side can supply. When it IS known, the step
  // reads as "verify this claim"; when it is not, the step reads as "find out, then report".
  //
  // What is NOT acceptable is a fabricated value in its place. A literal `<the controller's account>` reached a
  // real machine once and its agent did the sensible thing — it stopped and asked — which is a wasted round trip
  // and indistinguishable from a value somebody actually typed.
  const accountKnown = user !== '';
  const controller = accountKnown ? user : '本机实际的账号';
  // The panel's form gives every field as a string, so accept a numeric string too. Defaulting to 22
  // matches the machine-record default; an explicit port always wins.
  const requestedPort = Number.parseInt(String(options.port ?? ''), 10);
  const port = Number.isInteger(requestedPort) && requestedPort > 0 && requestedPort <= 65535
    ? String(requestedPort)
    : '22';

  // One substitution for every section, so a placeholder can never survive in one of them while being
  // filled in the others. That exact slip shipped once: the opening line still read `{CONTROLLER}`
  // while the steps below it carried the real name.
  const fill = (text) => text
    .replaceAll('{CONTROLLER}', controller)
    .replaceAll('{HOST}', host)
    .replaceAll('{PORT}', port)
    .replaceAll('{PUBLIC_KEY}', publicKey)
    .replaceAll('{KEY_IDENTITY}', keyIdentityOf(publicKey))
    // The controller's own address, for the machine to compare subnets against and to ping. Empty when there is
    // no callback — the copied prompt has no controller address to offer, and the address rule then falls back
    // to the exclusion list alone rather than naming a target it does not have.
    .replaceAll('{CALLBACK_HOST}', typeof options.callback?.address === 'string' ? options.callback.address : '');

  // The account paragraph is chosen here and substituted BEFORE `fill` runs, so the paragraph's own
  // `{CONTROLLER}` is resolved by the same pass. The other order would leave a literal `{CONTROLLER}` inside
  // the step — the exact class of bug the comment above records.
  const accountStep = accountKnown ? ACCOUNT_KNOWN : ACCOUNT_UNKNOWN;
  const step = (index, text) => fill(text.replace('{ACCOUNT_STEP}', accountStep))
    .replace(/^## /, `## 步骤 ${String(index + 1)}：`);

  // The reporting section exists only for the SERVED prompt: it names an address to report to, and a copied
  // prompt has none. Telling a machine to report into nowhere would be worse than saying nothing.
  const reporting = typeof options.callback?.url === 'string' && options.callback.url !== ''
    ? `${fill(REPORTING_STEP
      .replaceAll('{CALLBACK_URL}', options.callback.url)
      .replaceAll('{CALLBACK_TOKEN}', String(options.callback.token ?? '')))}\n\n`
    : '';

  return [
    fill(GOAL),
    '',
    reporting + step(0, SSHD_STEP),
    '',
    step(1, FIREWALL_STEP),
    '',
    step(2, PROFILE_STEP),
    '',
    step(3, KEY_STEP),
    '',
    fill(REPORT),
    '',
  ].join('\n');
}
/**
 * Assemble the onboarding answer: which key is on offer, and the prompt to carry across.
 *
 * @param deps - `{ subprocess, fs? }` seams.
 * @param options - `{ user, host, port, keyFile, sshDir }`. `port` defaults to the machine default when
 *   omitted, so the prompt still names a concrete port.
 * @returns `{ keyFile, keySource, fingerprint, prompt }`, or `{ problem, hint? }` when no key can be
 *   offered.
 */
export async function buildSetup(deps, options = {}) {
  const resolved = await resolveKey(deps, { sshDir: options.sshDir, preferredKey: options.keyFile });
  // A key the operator NAMED but that is not on disk is its own problem, not a reason to quietly use a
  // different one. Falling through to the scanned names would emit a prompt carrying a public key the operator
  // never chose — and the machine would then authorize that key. Say it instead.
  if (resolved.preferred !== undefined && resolved.preferredExists === false) {
    return {
      needs: 'key',
      problem: `the key named in the settings is not there: ${resolved.preferred} ／ 设置里指定的密钥不存在：${resolved.preferred}`,
      hint: 'Correct the key path in the shared settings, or clear it to let this page pick a key from your SSH directory. ／ 改正共享设置里的密钥路径，或者清空它、让本页从你的 SSH 目录里挑一把。',
      sshDir: resolved.sshDir,
      candidates: resolved.candidates,
    };
  }
  const candidates = [...new Set([
    ...(resolved.preferred === undefined ? [] : [resolved.preferred]),
    ...resolved.candidates,
  ])];
  if (candidates.length === 0) {
    const paths = generatedKeyPaths({ sshDir: resolved.sshDir });
    return {
      // `needs` is a discriminator, not decoration. This outcome and "the account is missing" are both a
      // `problem`, and the panel rendered ONE fixed message for either — telling an operator who had no key
      // problem at all that they had no key, beside a button that generates one. The panel now picks its
      // wording and its remedy from this value.
      needs: 'key',
      problem: 'this controller has no SSH key to offer ／ 这台主控机没有可用的 SSH 密钥',
      hint: `Generate one with a separate, approved step (ssh-keygen -t ed25519 -N "" -C ${GENERATED_KEY_COMMENT} -f ${paths.privateKey}), or name an existing private key in \`keyFile\`. ／ 用一个单独且已获批准的步骤生成一把（ssh-keygen -t ed25519 -N "" -C ${GENERATED_KEY_COMMENT} -f ${paths.privateKey}），或者在 \`keyFile\` 里指定一个已有的私钥。`,
      sshDir: resolved.sshDir,
      candidates,
      generated: paths,
    };
  }
  const privateKey = candidates[0];
  const read = await readPublicKey(deps, privateKey);
  if (read.problem !== undefined) return { needs: 'key-unreadable', problem: `cannot read the public half of ${privateKey}: ${read.problem} ／ 无法读取 ${privateKey} 的公钥部分：${read.problem}`, privateKey };
  // No `needs: 'user'` outcome exists. An account is optional, and its absence is not a failure: the account
  // lives on the controlled machine, the prompt sends that machine to find it, and the answer comes back in the
  // report step. Requiring it here was the controller demanding information only the other side can supply —
  // and it broke the one workflow that never needed it, a machine set up before it has been added.
  const prompt = buildSetupPrompt({ publicKey: read.publicKey, user: options.user, host: options.host, port: options.port, callback: options.callback });
  return {
    keyFile: keyPathForSsh(privateKey),
    keySource: read.source,
    // Reported so the CONTROLLER can recognize the key; the prompt deliberately asks the controlled
    // machine for the standard SSH fingerprint instead, since it cannot compute this one.
    fingerprint: read.fingerprint,
    prompt,
  };
}
